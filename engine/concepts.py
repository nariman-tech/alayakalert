"""Смысловой слой: сочетания понятий вместо точных фраз.

Мошенники постоянно перефразируют: «заплати — получишь», «закинь, тогда откроется сумма»,
«переведи, верну вдвое». Поэтому здесь признак срабатывает, когда в ОДНОМ сообщении встречаются
нужные понятия (каждое — большой словарь синонимов на русском, казахском и транслите),
независимо от порядка слов и формулировки.

Понятия:
    ОПЛАТА       заплати, оплати, переведи, скинь, закинь, пополни, внеси, вложи, аудар, төле, сал…
    ВЫГОДА       получишь, верну, выведешь, заберёшь, откроется, доход, процент, пайда, аласың…
    БОЛЬШЕ       вдвое, x2, в 3 раза, больше, %, или конкретная сумма
    СУММА        2к, 2 тыс, 2 тис, 2 мың, 2 000 ₸, 1,5 млн, 30 000 тг
    ВЫВОД        вывод, вывести, снять, сумма откроется, разблокировать, шығару
    УСЛОВИЕ      только после, сначала, тогда, чтобы, если
    УЧАСТИЕ      участие, билет, номерок, слот, вход, доступ к розыгрышу, қатысу
    ГАРАНТИЯ     гарантия, 100%, точно, без риска, без проигрыша, міндетті түрде, кепілдік
    ПРИГЛАШЕНИЕ  пригласи, приведи, привлеки, шақыр, в команду, с каждого
    ВЗНОС        взнос, вклад, депозит, салым
    УСЛОВИЯ      условия, подробности, детали, как участвовать
    ЛИЧКА        лс, личка, директ, админ, жеке хат, бот

Отрицание («без взноса», «никаких гарантий», «не гарантирует», «бесплатно») гасит понятие.
"""
from __future__ import annotations

import re

MONEY = re.compile(
    r"(?<![\w.])(\d{1,3}(?:[  ]\d{3})+|\d+(?:[.,]\d+)?)\s*(к|k|тыс\w*|тис\w*|мың|млн|миллион\w*|т|тг|тенге|₸)(?![а-яa-z])"
    r"|(?<![\w.])\d{1,3}(?:[  ]\d{3})+(?![\w.])|(?<![\w.,])\d{4,}(?![\w.,])")

PAY = re.compile(r"(заплат|оплат|переве|перевод|\bскин|закин|\bкинь|\bкину|пополн|\bвнес|\bвнос|влож|отправ|задонат|аудар|төле"
                 r"|\bсал(ыңыз|саң\w*|сақ|ып|да\b|\b)|додеп)")
# выгода, которая не является обещанием дохода: скидка, кэшбэк, баллы, подарок за покупку
NOT_PROFIT = re.compile(r"(скидк|кэшб|кешб|cashback|балл|жеңілдік|футболк|сертификат на скидк|рассрочк)")
GAIN = re.compile(r"(получ|\bверн|выведе|вывод|забер|забира|откро|разблок|начисл|доход|прибыл|пайда|табыс|процент|\bплюс\b"
                  r"|профит|заработ|аласың|аласыз|алыңыз|алады|қайтар|удво|вдвое|окуп|увелич|умнож|вырастет|артады|көбейеді)")
MORE = re.compile(r"(вдвое|удво|(?<![\w.])[xх]\s?\d|в\s+\d+\s+раз|в\s+(два|три|четыре|пять|несколько)\s+раз|больше|\d+\s*%|процент|екі есе|үш есе)")
WITHDRAW = re.compile(r"(вывод|вывест|вывести|\bснять|снятие|сумм\w*\s+(\w+\s+)?откро|откро\w*\s+(\w+\s+)?сумм|разблокир|шығар)")
COND = re.compile(r"(только после|после того|сначала|\bтогда\b|\bчтобы\b|\bесли\b|для того|иначе|\bсосын\b|кейін)")
FEE = re.compile(r"(пополн|оплат|комисс|депозит|взнос|налог|страховк|заплат|доплат|төле|ещ[её]\s+раз\s+(\w+\s+)?(закин|скин|пополн))")
PARTICIPATE = re.compile(r"(участи|участв|билет|номерок|номер\w* участ|\bслот|\bвход\b|доступ\w*\s+(\w+\s+){0,2}розыгр|қатыс)")
GIVEAWAY = re.compile(r"(розыгр|разыгр|\bприз|ұтыс|сыйлық|жүлде|конкурс|\bгив|giveaway|лотере)")
GUARANTEE = re.compile(r"(гарант|(?<!\d)100\s*%|сто процентов|точно будет|без риск|без проигрыш|міндетті түрде|кепілд|наверняка|железн\w* (схем|проход|ставк))")
INVITE = re.compile(r"(пригла|приведи|приводи|привлек|привлеч|шақыр|в команду|в структуру|рефер|\bреф\b|с каждого)")
CONTRIB = re.compile(r"(взнос|вклад|депозит|салым|вложени)")
TERMS = re.compile(r"(услови|подробност|детал|\bинф[оа]\b|как участвовать|правила)")
PRIVATE = re.compile(r"(\bлс\b|личк|личн\w*\s+сообщ|директ|\bадмин|в лич|жеке\w*\s+(хат|чат)|в бот)")
INCOME = re.compile(r"(получ\w*|будет|жд[её]т|ждут|ал(асың|асыз|ады))\s+(\w+\s+)?(повышенн\w*\s+|высок\w*\s+|гарантированн\w*\s+|пассивн\w*\s+|хорош\w*\s+)?"
                    r"(доход|прибыл|процент|пайда|табыс|\bплюс)")
FREE = re.compile(r"(бесплатн|тегін|ақысыз|без (оплат|взнос|вложен)|ничего (не )?платить|платить не нужно)")
GAMBLING_SLANG = re.compile(r"(\bпроход(ы|ов|ами|ом)?\b|экспресс\w*\s+(на|дня|ставк)|\bкэф\w*|сигнал\w*\s+(на|для)\s+(авиатор|краш|слот|ставк)"
                            r"|\bзаход\w*\s+(на|в|по)\s+(\d|x|х|ставк|слот)|ставочк|додеп|депчик|казик|слотик|\bспин\w*|отыгр\w*)")
NEG = re.compile(r"(\bне|\bнет|\bбез|\bникаких|\bникакой|\bникакого|\bни)\s+(\w+\s+)?$")
LEGIT_TERMS = re.compile(r"(официальн|опубликован|по правилам|условия опубликован|правила (выложены|опубликован))")


def _first(rx: re.Pattern, text: str, skip_negated: bool = True):
    for m in rx.finditer(text):
        if skip_negated and NEG.search(text[max(0, m.start() - 25): m.start()]):
            continue
        return m
    return None


def detect(units, add) -> None:
    """units — список Unit (msg, orig, norm); add(signal_id, evidence, note) — из signals.detect_text."""
    by_msg: dict[int, list] = {}
    for u in units:
        by_msg.setdefault(u.msg, []).append(u)
    doc = "\n".join(u.norm for u in units)
    giveaway_doc = bool(GIVEAWAY.search(doc))

    for msg, us in by_msg.items():
        text = " ".join(u.norm for u in us)
        quote = [{"msg": msg, "text": _short(" ".join(u.orig for u in us))}]
        free_here = bool(FREE.search(text))

        # «Заплати — получишь больше»: оплата раньше выгоды, после выгоды — сумма или «больше»
        pay = _first(PAY, text)
        if pay:
            gain = None
            for g in GAIN.finditer(text, pay.end()):
                if not NEG.search(text[max(0, g.start() - 25): g.start()]):
                    gain = g
                    break
            if (gain and (MORE.search(text, gain.start()) or MONEY.search(text, gain.start())) and not free_here
                    and not NOT_PROFIT.search(text[gain.start(): gain.start() + 40])):
                add("X_PAY_TO_GET", quote, "сочетание: оплата → выгода → больше")

        # Плата за вывод: вывод + платёж + условие
        if WITHDRAW.search(text) and _first(FEE, text) and COND.search(text):
            add("X_WITHDRAW_FEE", quote, "сочетание: вывод + доплата + условие")

        # Платное участие в розыгрыше: участие + оплата или сумма, без «бесплатно»
        if giveaway_doc and not free_here:
            part = _first(PARTICIPATE, text)
            if part and (_first(PAY, text) or MONEY.search(text)):
                add("T1_PAID", quote, "сочетание: участие + оплата или сумма")

        # Гарантия выигрыша или дохода (не «никаких гарантий»)
        g = _first(GUARANTEE, text)
        if g and (GAIN.search(text) or GAMBLING_SLANG.search(text) or re.search(r"(выигр|приз|казино|слот|ставк)", text)):
            add("T3_GUARANTEE", quote, "гарантия выигрыша или дохода")

        # Казино-сленг
        if _first(GAMBLING_SLANG, text):
            add("T2_GAMBLING", quote, "игровой сленг")

        # Доход от взносов приглашённых
        if _first(INVITE, text) and GAIN.search(text):
            add("T3_REFERRAL", quote, "сочетание: приглашение + выгода")
            if CONTRIB.search(text):
                add("T3_NEW_MONEY", quote, "сочетание: приглашение + выгода + взносы")

        # Обещание дохода
        if _first(INCOME, text):
            add("T3_EASY_INCOME", quote, "обещание дохода")

        # Условия розыгрыша только в личке
        if giveaway_doc and TERMS.search(text) and PRIVATE.search(text) and not LEGIT_TERMS.search(text):
            add("T1_HIDDEN_TERMS", quote, "условия не опубликованы, только в личке")


def _short(s: str, n: int = 180) -> str:
    s = " ".join(s.split())
    return s if len(s) <= n else s[: n - 1] + "…"
