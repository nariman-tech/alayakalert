WEIGHTS = {"high": 30, "medium": 15, "low": 5}


@dataclass
class SignalDef:
    id: str
    track: int
    weight: str               # high / medium / low / dampener
    title: str
    hint: str
    points: int = 0

    def __post_init__(self):
        if not self.points:
            self.points = WEIGHTS.get(self.weight, 0)


CATALOG: dict[str, SignalDef] = {}


def _def(id, track, weight, title, hint, points=0):
    CATALOG[id] = SignalDef(id, track, weight, title, hint, points)


