def telegram() -> dict:
    t = datetime(2026, 10, 1, 19, 0)
    msgs, i = [], 0
    for k in range(4):
        for author, text in CHIT_CHAT:
            i += 1
            t += timedelta(minutes=37 + k * 11)
            msgs.append({"id": i, "type": "message", "date": t.isoformat(), "date_unixtime": str(int(t.timestamp())),
                         "from": author, "from_id": f"user{abs(hash(author)) % 100000}", "text": text})
    for author, text in SCHEME:
        i += 1
        t += timedelta(minutes=23)
        m = {"id": i, "type": "message", "date": t.isoformat(), "date_unixtime": str(int(t.timestamp())),
             "from": author, "from_id": f"user{abs(hash(author)) % 100000}",
             "text": [{"type": "plain", "text": text}] if "Kaspi" in text else text}
        if "Выплата пришла" in text:
            m["photo"] = "photos/photo_1@12-10-2026_20-15-00.jpg"
        msgs.append(m)
    msgs.insert(3, {"id": 999, "type": "service", "date": msgs[2]["date"], "actor": "Айгуль Береке", "action": "invite_members"})
    return {"name": "Клуб «Береке» 💰", "type": "private_supergroup", "id": 1234567890, "messages": msgs}


